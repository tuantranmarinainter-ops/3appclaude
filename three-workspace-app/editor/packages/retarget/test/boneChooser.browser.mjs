import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(new URL('../../../apps/studio/package.json', import.meta.url))
const { chromium } = require('playwright')
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 640, height: 480 } })
  await page.route('http://chooser.test/**', route => {
    const module = route.request().url().endsWith('/bone-chooser.js')
    return route.fulfill({ contentType: module ? 'text/javascript' : 'text/html', body: module ? readFileSync(new URL('../workbench/public/bone-chooser.js', import.meta.url), 'utf8') : '<html><body></body></html>' })
  })
  await page.goto('http://chooser.test/')
  await page.evaluate(async () => {
    const { boneChooser } = await import('/bone-chooser.js')
    const style = document.createElement('style')
    style.textContent = '.bone-options { position:fixed; overflow-y:auto; box-sizing:border-box } [role=option] { padding:8px }'
    document.head.append(style)
    const input = document.createElement('input')
    input.setAttribute('aria-label', 'Xương nguồn thử')
    document.body.append(boneChooser(input, Array.from({ length:84 }, (_, i) => `Bone${i}`), name => { window.selected = name }))
  })
  const input = page.getByRole('combobox')
  await page.getByRole('button').click()
  assert.equal(await page.getByRole('option').count(), 84)
  const popup = page.getByRole('listbox')
  const bounds = await popup.boundingBox()
  await page.mouse.move(bounds.x + 20, bounds.y + 20)
  await page.mouse.wheel(0, 5000)
  await page.waitForFunction(() => document.querySelector('[role=listbox]').scrollTop > 0)
  await page.getByRole('option', { name:'Bone83', exact:true }).click()
  assert.equal(await page.evaluate(() => window.selected), 'Bone83')
  await input.fill('Bone82')
  await input.press('ArrowDown')
  await input.press('Enter')
  assert.equal(await page.evaluate(() => window.selected), 'Bone82')
  await input.press('ArrowUp')
  await input.press('Enter')
  assert.equal(await page.evaluate(() => window.selected), 'Bone83')
  await page.getByRole('button').click()
  await page.setViewportSize({ width:320, height:180 })
  await page.waitForFunction(() => { const r = document.querySelector('[role=listbox]').getBoundingClientRect(); return r.bottom <= innerHeight && r.right <= innerWidth })
  const small = await popup.boundingBox()
  assert.ok(small.x >= 0 && small.y >= 0 && small.x + small.width <= 320 && small.y + small.height <= 180)
  await input.press('Escape')
  assert.equal(await popup.count(), 0)
  await page.getByRole('button').click()
  await page.evaluate(() => { document.querySelector('.bone-chooser').style.transform = 'translateY(1000px)'; window.dispatchEvent(new Event('resize')) })
  assert.equal(await popup.count(), 0)
  console.log('PASS: 84 bones, real wheel, filter, arrows, Enter, Escape, resize and offscreen cleanup')
} finally { await browser.close() }
